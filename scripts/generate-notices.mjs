import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(root, "THIRD_PARTY_NOTICES.md");
const check = process.argv.includes("--check");
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
let output = `# Third-party notices

Generated by \`node scripts/generate-notices.mjs\` from the locked dependency
inventory and actual installed package files. Includes development/build tools;
it does not grant a license to Foody itself. Instrument Sans is served locally
under the SIL Open Font License; Lucide and other runtime dependencies retain
their own notices below.

All lockfile packages are listed, including optional packages unavailable on the
current platform. Complete notice texts are included wherever installed package
files provide them. Metadata alone is not a substitute for license terms. Review
unavailable or missing notices before distributing the corresponding binaries.
When preparing a release for another platform, regenerate on that platform too.

The output is deterministic for the same lockfile and installed package files;
it records no timestamp, machine path or environment variables. Copyright names,
upstream project URLs and contacts within license texts are preserved.

`;
let count = 0;
for (const relative of Object.keys(lock.packages).sort()) {
  if (!relative) continue;
  if (
    !relative.startsWith("node_modules/") ||
    relative.split("/").includes("..")
  ) {
    throw new Error("Unsupported dependency location in lockfile");
  }
  const entry = lock.packages[relative];
  const directory = join(root, relative);
  const packagePath = join(directory, "package.json");
  const installed = existsSync(packagePath);
  const pkg = installed ? JSON.parse(readFileSync(packagePath, "utf8")) : entry;
  const name = pkg.name || relative.split("node_modules/").at(-1);
  if (installed && pkg.version !== entry.version) {
    throw new Error(`Installed package differs from lockfile: ${relative}`);
  }
  const license = pkg.license ?? entry.license ?? "not declared";
  const metadata =
    typeof license === "string" ? license : JSON.stringify(license);
  output += `## ${name} ${entry.version}\n\nLicense metadata: \`${metadata}\`${entry.dev ? " (development/build dependency)." : "."}\n\n`;
  if (!installed) {
    output +=
      "Not installed on this platform; no local license text available.\n\n";
  } else {
    const notices = readdirSync(directory)
      .filter(
        (name) =>
          /^(licen[sc]e|copying|notice)(\.|$|-)/i.test(name) &&
          statSync(join(directory, name)).isFile(),
      )
      .sort();
    if (!notices.length) {
      output +=
        "No standalone license or notice file present in the installed package.\n\n";
    }
    for (const notice of notices) {
      const content = readFileSync(join(directory, notice), "utf8")
        .replace(/\r\n/g, "\n")
        .trim();
      // A long fence also preserves any Markdown fences embedded in upstream text.
      const fence = "`".repeat(
        Math.max(
          3,
          ...[...content.matchAll(/`+/g)].map((match) => match[0].length + 1),
        ),
      );
      output += `### ${notice}\n\n${fence}text\n${content}\n${fence}\n\n`;
    }
  }
  count++;
}
output = await format(output, { parser: "markdown" });
if (check) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== output) {
    console.error(
      "Third-party notices differ; run node scripts/generate-notices.mjs and review the changes.",
    );
    process.exitCode = 1;
  } else {
    console.log(`Third-party notices match ${count} locked packages.`);
  }
} else {
  writeFileSync(target, output);
  console.log(`Wrote third-party notices for ${count} locked packages.`);
}
